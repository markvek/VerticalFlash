import { z } from "zod";
import { randomUUID } from "crypto";
import { getGeminiClient, GEMINI_MODEL } from "./gemini";
import {
  HUMAN_SCORE_METRICS,
  type BenchmarkAiReview,
  type BenchmarkRun,
  type HumanScoreMetric,
} from "./benchmark-schema";

// The AI judge reads only the storyboard text (no video) and assesses each variant’s
// storytelling qualities. It is blind to provider identity — it
// sees each variant by its blind label only — and its scores are advisory:
// they sit alongside human reviews and never overwrite them.

function variantBlock(
  blindLabel: string,
  storyboard: NonNullable<
    NonNullable<BenchmarkRun["variants"][number]["artifact"]>["storyboard"]
  >,
  broll: NonNullable<BenchmarkRun["variants"][number]["artifact"]>["broll"],
): string {
  const beats = storyboard.beats
    .map((beat, index) => {
      const cut = broll?.find((decision) => decision.beat === index);
      const brollLine = cut?.filename
        ? ` [B-roll: ${cut.filename}]`
        : "";
      const onScreen = beat.on_screen_text ? ` (on-screen: "${beat.on_screen_text}")` : "";
      return `  ${index + 1}. [${beat.section}] ${beat.text}${onScreen}${brollLine}`;
    })
    .join("\n");
  return `### ${blindLabel}\nTitle: ${storyboard.title}\nAngle: ${storyboard.angle}\nBeats:\n${beats}`;
}

export const JudgeResponseZ = z.object({
  winner: z.string().min(1),
  variants: z.array(z.object({
    label: z.string().min(1), virality: z.number().min(0).max(100),
    hook: z.number().min(1).max(10), pacing: z.number().min(1).max(10),
    clarity: z.number().min(1).max(10), polish: z.number().min(1).max(10),
    broll_fit: z.number().min(1).max(10), wouldPost: z.boolean(), rationale: z.string().min(1),
  })).min(1),
});

export function parseJudgeResponse(text: string, labels: string[]) {
  const parsed = JudgeResponseZ.parse(JSON.parse(text));
  const returned = new Set(parsed.variants.map(v => v.label));
  if (returned.size !== labels.length || parsed.variants.length !== labels.length ||
      labels.some(label => !returned.has(label)) || !returned.has(parsed.winner))
    throw new Error("AI review must score each variant exactly once and choose a valid winner");
  return parsed;
}

export async function judgeStoryboardBenchmark(
  run: BenchmarkRun,
): Promise<BenchmarkAiReview | null> {
  const ready = run.variants.filter(
    (variant) => variant.status === "ready" && variant.artifact?.storyboard,
  );
  if (ready.length === 0) return null;

  const brief =
    run.execution?.input.request.brief?.trim() ||
    "Choose the strongest story from the footage.";
  const allowBroll = !!run.execution?.input.request.allow_broll;
  const seconds = run.execution?.input.request.lengths[0];

  const blocks = ready
    .map((variant) =>
      variantBlock(
        variant.blindLabel,
        variant.artifact!.storyboard!,
        variant.artifact!.broll,
      ),
    )
    .join("\n\n");

  const prompt = `You are a ruthless short-form video growth strategist judging vertical TikTok/Reels storyboards.
Judge MOSTLY FOR VIRALITY: hook strength in the first 1-2 seconds, scroll-stopping curiosity, retention across the whole cut, a satisfying payoff, shareability, and how well it fits current short-form trends. Reward bold, specific, tension-driven storytelling; penalize slow starts, vague hooks, and generic filler.
Each storyboard was generated by a different AI model from the SAME source footage and brief. You do not know which model made which — judge only the storyboard text.

Creative brief: ${brief}
Target length: ${seconds ?? "unknown"} seconds. B-roll is ${allowBroll ? "enabled" : "disabled"}.

Score every variant. "virality" is a 0-100 editorial assessment of the storyboard text, not a prediction of views or audience performance. Also rate hook, pacing, clarity, polish, and broll_fit from 1-10${allowBroll ? "" : " (rate broll_fit as 5 since B-roll is disabled)"}. Set "wouldPost" to true only if you would publish it as-is. Pick the single most viral variant as "winner" (use its label). Keep each "rationale" to 1-2 sentences focused on virality.

Return ONLY a JSON object shaped exactly like:
{"winner":"<label>","variants":[{"label":"<label>","virality":0,"hook":1,"pacing":1,"clarity":1,"polish":1,"broll_fit":1,"wouldPost":false,"rationale":""}]}

Variants:
${blocks}`;

  const response = await getGeminiClient().models.generateContent({
    model: GEMINI_MODEL,
    contents: [{ role: "user", parts: [{ text: prompt }] }],
    config: { responseMimeType: "application/json" },
  });

  const parsed = parseJudgeResponse(response.text ?? "{}", ready.map(v => v.blindLabel));
  const judged = new Map(
    (parsed.variants ?? [])
      .filter((entry) => typeof entry.label === "string")
      .map((entry) => [entry.label as string, entry]),
  );

  const reviews = ready.map((variant) => {
    const entry = judged.get(variant.blindLabel)!;
    const scores = Object.fromEntries(
      HUMAN_SCORE_METRICS.map((metric) => [metric, entry[metric]]),
    ) as Record<HumanScoreMetric, number>;
    return {
      variantId: variant.id,
      virality: entry.virality,
      scores,
      wouldPost: !!entry.wouldPost,
      rationale: (entry.rationale ?? "").slice(0, 2000),
    };
  });

  const winnerByLabel = ready.find(
    (variant) => variant.blindLabel === parsed.winner,
  );
  const winnerVariantId =
    winnerByLabel?.id ??
    reviews.reduce(
      (best, review) =>
        review.virality > (best?.virality ?? -1) ? review : best,
      reviews[0],
    )?.variantId ??
    null;

  return {
    id: randomUUID(),
    createdAt: new Date().toISOString(),
    judgeModel: response.modelVersion || GEMINI_MODEL,
    winnerVariantId,
    reviews,
  };
}
